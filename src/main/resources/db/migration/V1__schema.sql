CREATE TABLE app_user (
    id VARCHAR(32) PRIMARY KEY,
    display_name VARCHAR(100) NOT NULL,
    role VARCHAR(20) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_app_user_role CHECK (role IN ('CUSTOMER', 'AGENT', 'ADMIN'))
);

CREATE TABLE customer_order (
    id VARCHAR(32) PRIMARY KEY,
    user_id VARCHAR(32) NOT NULL,
    status VARCHAR(30) NOT NULL,
    total_amount DECIMAL(12, 2) NOT NULL,
    refundable_amount DECIMAL(12, 2) NOT NULL,
    currency VARCHAR(8) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_order_user FOREIGN KEY (user_id) REFERENCES app_user(id),
    CONSTRAINT ck_order_refundable CHECK (refundable_amount >= 0)
);

CREATE TABLE support_ticket (
    id VARCHAR(32) PRIMARY KEY,
    user_id VARCHAR(32) NOT NULL,
    order_id VARCHAR(32),
    conversation_id VARCHAR(64),
    category VARCHAR(30) NOT NULL,
    subject VARCHAR(200) NOT NULL,
    status VARCHAR(30) NOT NULL,
    priority VARCHAR(10) NOT NULL,
    assigned_agent_id VARCHAR(32),
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_ticket_user FOREIGN KEY (user_id) REFERENCES app_user(id),
    CONSTRAINT fk_ticket_order FOREIGN KEY (order_id) REFERENCES customer_order(id),
    CONSTRAINT fk_ticket_agent FOREIGN KEY (assigned_agent_id) REFERENCES app_user(id)
);

CREATE TABLE refund_request (
    id VARCHAR(32) PRIMARY KEY,
    order_id VARCHAR(32) NOT NULL,
    user_id VARCHAR(32) NOT NULL,
    conversation_id VARCHAR(64) NOT NULL,
    amount DECIMAL(12, 2) NOT NULL,
    reason VARCHAR(300) NOT NULL,
    status VARCHAR(30) NOT NULL,
    idempotency_key VARCHAR(160) NOT NULL UNIQUE,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_refund_order FOREIGN KEY (order_id) REFERENCES customer_order(id),
    CONSTRAINT fk_refund_user FOREIGN KEY (user_id) REFERENCES app_user(id),
    CONSTRAINT ck_refund_amount CHECK (amount > 0)
);

CREATE TABLE conversation (
    id VARCHAR(64) PRIMARY KEY,
    user_id VARCHAR(32) NOT NULL,
    status VARCHAR(30) NOT NULL,
    intent VARCHAR(40),
    confidence DOUBLE,
    state_json CLOB NOT NULL,
    last_question VARCHAR(500),
    message_count INT NOT NULL,
    version BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_conversation_user FOREIGN KEY (user_id) REFERENCES app_user(id)
);

CREATE TABLE conversation_message (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id VARCHAR(64) NOT NULL,
    role VARCHAR(20) NOT NULL,
    content CLOB NOT NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_message_conversation FOREIGN KEY (conversation_id) REFERENCES conversation(id)
);

CREATE TABLE tool_invocation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id VARCHAR(64) NOT NULL,
    trace_id VARCHAR(64) NOT NULL,
    tool_name VARCHAR(40) NOT NULL,
    input_json CLOB NOT NULL,
    output_json CLOB NOT NULL,
    success BOOLEAN NOT NULL,
    error_code VARCHAR(60),
    latency_ms BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_tool_conversation FOREIGN KEY (conversation_id) REFERENCES conversation(id)
);

CREATE TABLE audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trace_id VARCHAR(64) NOT NULL,
    actor_id VARCHAR(32) NOT NULL,
    actor_role VARCHAR(20) NOT NULL,
    action VARCHAR(80) NOT NULL,
    resource_type VARCHAR(40) NOT NULL,
    resource_id VARCHAR(64),
    outcome VARCHAR(20) NOT NULL,
    detail_json CLOB,
    created_at TIMESTAMP NOT NULL
);

CREATE TABLE chat_request (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id VARCHAR(32) NOT NULL,
    idempotency_key VARCHAR(120) NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    response_json CLOB NOT NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT uk_chat_request_idempotency UNIQUE (user_id, idempotency_key)
);

CREATE INDEX idx_order_user ON customer_order(user_id);
CREATE INDEX idx_ticket_user ON support_ticket(user_id);
CREATE INDEX idx_ticket_conversation ON support_ticket(conversation_id);
CREATE INDEX idx_ticket_agent_status ON support_ticket(assigned_agent_id, status);
CREATE INDEX idx_refund_conversation ON refund_request(conversation_id, order_id);
CREATE INDEX idx_message_conversation ON conversation_message(conversation_id);
CREATE INDEX idx_tool_conversation ON tool_invocation(conversation_id);
CREATE INDEX idx_audit_conversation ON audit_log(resource_id);

